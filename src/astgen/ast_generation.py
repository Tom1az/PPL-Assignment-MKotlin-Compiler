"""AST generation for MKotlin — Assignment 2.

Implement ``ASTGeneration`` by overriding the visit methods of the generated
``MKotlinVisitor`` (produced by ANTLR from ``src/grammar/MKotlin.g4`` after you
run ``python3 run.py build``).  Each visit method must return the appropriate
node object from ``src/utils/nodes.py``.  See ``mkotlin-ast_representation.md``
for mapping conventions and ``repr()`` formats used in tests.

This file is a skeleton: it raises ``NotImplementedError`` until you implement
it.  The import of the generated visitor is wrapped so that the file can be
imported even before the grammar has been built (e.g. during ``run.py check``).
"""

from src.utils import nodes

try:
    # Generated by ANTLR after `python3 run.py build`.
    from src.grammar.MKotlinVisitor import MKotlinVisitor
    from src.grammar.MKotlinParser import MKotlinParser
    _BASE = MKotlinVisitor
except Exception:  # pragma: no cover - grammar not built yet
    _BASE = object
    MKotlinParser = None


class ASTGeneration(_BASE):
    """Walk the ANTLR parse tree and build an AST of ``nodes`` objects."""

    # ----------------------------------------------------------------- #
    #  TODO (Assignment 2): override the generated visit* methods.       #
    #                                                                    #
    #  Example skeleton for the top-level rule:                          #
    #                                                                    #
    #  def visitProgram(self, ctx):                                      #
    #      decls = []                                                    #
    #      if ctx.declList():                                            #
    #          decls = self.visit(ctx.declList())                        #
    #      return nodes.Program(decls)                                   #
    # ----------------------------------------------------------------- #
    def visitProgram(self, ctx):
        return nodes.Program(self.visit(ctx.declList()))
    
    def visitDeclList(self, ctx):
        return self.visit(ctx.declPrime()) if ctx.declPrime() else []

    def visitDeclPrime(self, ctx):
        return [self.visit(ctx.decl())] + self.visit(ctx.declPrime()) if ctx.declPrime() else [self.visit(ctx.decl())]
    
    def visitDecl(self, ctx):
        if ctx.dataClassDecl():
            return self.visit(ctx.dataClassDecl())
        elif ctx.funcDecl():
            return self.visit(ctx.funcDecl())

    def visitDataClassDecl(self, ctx):
        return nodes.DataClassDecl(ctx.IDENT().getText(), self.visit(ctx.memList()) if ctx.memList() else [])

    def visitMemList(self, ctx):
        return [self.visit(ctx.mem())] + self.visit(ctx.memList()) if ctx.memList() else [self.visit(ctx.mem())]

    def visitMem(self, ctx):
        return nodes.MemberDecl(ctx.IDENT().getText(), self.visit(ctx.typ()))

    def visitTyp(self, ctx):
        if ctx.INT():
            return nodes.IntType()
        elif ctx.FLOAT():
            return nodes.FloatType()
        elif ctx.BOOLEAN():
            return nodes.BoolType()
        elif ctx.STRING():
            return nodes.StringType()
        elif ctx.IDENT():
            return nodes.ClassType(ctx.IDENT().getText())

    def visitFuncDecl(self, ctx):
        return nodes.FuncDecl(ctx.IDENT().getText(), self.visit(ctx.paramList()), self.visit(ctx.rettype()), self.visit(ctx.body()))

    def visitParamList(self, ctx):
        return self.visit(ctx.paramPrime()) if ctx.paramPrime() else []
    
    def visitParamPrime(self, ctx):
        return [self.visit(ctx.param())] + self.visit(ctx.paramPrime()) if ctx.paramPrime() else [self.visit(ctx.param())]

    def visitParam(self, ctx):
        return nodes.Param(ctx.IDENT().getText(), self.visit(ctx.typ()))

    def visitBody(self, ctx):
        return nodes.Block(self.visit(ctx.stmtList()))

    def visitRettype(self, ctx):
        return self.visit(ctx.returnableTyp()) if ctx.returnableTyp() else None
    
    def visitReturnableTyp(self, ctx):
        if ctx.typ():
            return self.visit(ctx.typ())
        elif ctx.UNIT():
            return nodes.UnitType()

    def visitStmtList(self, ctx):
        return self.visit(ctx.stmtPrime()) if ctx.stmtPrime() else []

    def visitStmtPrime(self, ctx):
        return [self.visit(ctx.stmt())] + self.visit(ctx.stmtPrime()) if ctx.stmtPrime() else [self.visit(ctx.stmt())]

    def visitStmt(self, ctx):
        if ctx.valdecl():
            return self.visit(ctx.valdecl())
        elif ctx.blkstmt():
            return self.visit(ctx.blkstmt())
        elif ctx.ifstmt():
            return self.visit(ctx.ifstmt())
        elif ctx.whilestmt():
            return self.visit(ctx.whilestmt())
        elif ctx.forstmt():
            return self.visit(ctx.forstmt())
        elif ctx.whenstmt():
            return self.visit(ctx.whenstmt())
        elif ctx.brkstmt():
            return self.visit(ctx.brkstmt())
        elif ctx.contstmt():
            return self.visit(ctx.contstmt())
        elif ctx.retstmt():
            return self.visit(ctx.retstmt())
        elif ctx.exprstmt():
            return self.visit(ctx.exprstmt())
    
    def visitValdecl(self, ctx):
        if ctx.VAL():
            return nodes.VarDecl(ctx.IDENT().getText(), False, self.visit(ctx.typ()) if ctx.typ() else None, self.visit(ctx.expr()))
        elif ctx.VAR():
            return nodes.VarDecl(ctx.IDENT().getText(), True, self.visit(ctx.typ()) if ctx.typ() else None, self.visit(ctx.expr()) if ctx.expr() else None)

    def visitBlkstmt(self, ctx):
        return nodes.Block(self.visit(ctx.stmtList()))

    def visitIfstmt(self, ctx):
        return nodes.If(self.visit(ctx.expr()), self.visit(ctx.stmt(0)), self.visit(ctx.stmt(1)) if ctx.stmt(1) else None)

    def visitWhilestmt(self, ctx):
        return nodes.While(self.visit(ctx.expr()), self.visit(ctx.stmt()))

    def visitForstmt(self, ctx):
        return nodes.For(ctx.IDENT().getText(), self.visit(ctx.expr(0)), self.visit(ctx.expr(1)), self.visit(ctx.stmt()))

    def visitWhenstmt(self, ctx):
        if ctx.expr():
            return nodes.When(self.visit(ctx.expr()), self.visit(ctx.whenStmtSubjBranchList()))
        else:
            return nodes.When(None, self.visit(ctx.whenStmtConditionlessBranchList()))

    def visitWhenStmtSubjBranchList(self, ctx):
        return [self.visit(ctx.whenStmtSubjBranch())] + self.visit(ctx.whenStmtSubjBranchList()) if ctx.whenStmtSubjBranchList() else [self.visit(ctx.whenStmtSubjBranch())]

    def visitWhenStmtConditionlessBranchList(self, ctx):
        return [self.visit(ctx.whenStmtConditionlessBranch())] + self.visit(ctx.whenStmtConditionlessBranchList()) if ctx.whenStmtConditionlessBranchList() else [self.visit(ctx.whenStmtConditionlessBranch())]

    def visitWhenStmtSubjBranch(self, ctx):
        if ctx.exprPrime():
            return nodes.WhenBranch(self.visit(ctx.exprPrime()), self.visit(ctx.stmt()))
        else:
            return nodes.WhenBranch(None, self.visit(ctx.stmt()))

    def visitWhenStmtConditionlessBranch(self, ctx):
        if ctx.expr():
            return nodes.WhenBranch([self.visit(ctx.expr())], self.visit(ctx.stmt()))
        else:
            return nodes.WhenBranch(None, self.visit(ctx.stmt()))

    def visitBrkstmt(self, ctx):
        return nodes.Break()

    def visitContstmt(self, ctx):
        return nodes.Continue()

    def visitRetstmt(self, ctx):
        return nodes.Return(self.visit(ctx.expr()) if ctx.expr() else None)

    def visitExprstmt(self, ctx):
        return nodes.ExprStmt(self.visit(ctx.expr()))
    